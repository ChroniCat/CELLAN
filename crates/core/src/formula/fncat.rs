/// 函数属于哪个类别
pub fn category(name: &str) -> &'static str {
    if let Some((_, c)) = TABLE.iter().find(|(n, _)| n.eq_ignore_ascii_case(name)) {
        return c;
    }
    for (p, c) in RULES {
        if name.to_ascii_uppercase().starts_with(p) {
            return c;
        }
    }
    "其他"
}

