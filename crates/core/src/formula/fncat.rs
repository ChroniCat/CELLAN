/// 查询函数参数签名（静态切片，大小写不敏感）。
pub fn signature_ref(name: &str) -> Option<&'static str> {
    let up = name.to_ascii_uppercase();
    DOCS.binary_search_by(|(n, _, _)| (*n).cmp(up.as_str()))
        .ok()
        .map(|idx| DOCS[idx].1)
}

/// 返回函数参数签名；若为未收录自定义名则回退为 `NAME(参数…)`。
pub fn signature(name: &str) -> String {
    if let Some(sig) = signature_ref(name) {
        sig.to_string()
    } else {
        format!("{}(参数…)", name.to_ascii_uppercase())
    }
}

/// 返回函数的简明中文说明。
pub fn description(name: &str) -> &'static str {
    let up = name.to_ascii_uppercase();
    DOCS.binary_search_by(|(n, _, _)| (*n).cmp(up.as_str()))
        .ok()
        .map(|idx| DOCS[idx].2)
        .unwrap_or("函数")
}
